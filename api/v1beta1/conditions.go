package v1beta1

import clusterv1 "sigs.k8s.io/cluster-api/api/core/v1beta2"

// Conditions and condition Reasons for the TalosControlPlane object.
//
// These constants describe the v1beta2 (metav1.Condition) shape that is the new contract
// surface. Legacy v1beta1-style condition constants live in the v1alpha3 package because
// only the legacy API still emits them.

const (
	// MachinesAllReadyCondition reports an aggregate of current status of the machines controlled by the TalosControlPlane.
	MachinesAllReadyCondition = "MachinesAllReady"
)

const (
	// MachinesBootstrapped is tracking control planes bootstrap status.
	MachinesBootstrapped = "MachinesBootstrapped"

	// WaitingForMachinesReason (Severity=Info) documents a TalosControlPlane bootstrap is waiting
	// for all control plane nodes to be created.
	WaitingForMachinesReason = "WaitingForMachines"

	// MachinesBootstrappedReason documents that all control plane machines have been bootstrapped.
	MachinesBootstrappedReason = "MachinesBootstrapped"
)

const (
	// AvailableCondition documents that the first control plane instance has completed Talos boot sequence
	// and so the control plane is available and an API server instance is ready for processing requests.
	AvailableCondition = "Available"

	// WaitingForTalosBootReason (Severity=Info) documents a TalosControlPlane object waiting for the first
	// control plane instance to complete Talos boot sequence.
	WaitingForTalosBootReason = "WaitingForTalosBoot"

	// InvalidControlPlaneConfigReason (Severity=Error) documents that controlplane config is invalid and the provider
	// can not proceed with the bootstrap.
	InvalidControlPlaneConfigReason = "InvalidControlPlaneConfig"

	// AvailableReason documents that the TalosControlPlane is available.
	AvailableReason = "Available"
)

const (
	// MachinesSpecUpToDateCondition documents that the spec of the machines controlled by the TalosControlPlane
	// is up to date. When this condition is false, the TalosControlPlane is executing a rolling upgrade.
	MachinesSpecUpToDateCondition = "MachinesSpecUpToDate"

	// RollingUpdateInProgressReason (Severity=Warning) documents a TalosControlPlane object executing a
	// rolling upgrade for aligning the machines spec to the desired state.
	RollingUpdateInProgressReason = "RollingUpdateInProgress"

	// InPlaceUpdateInProgressReason documents a TalosControlPlane object updating machines in place,
	// one at a time, to align their spec to the desired state.
	InPlaceUpdateInProgressReason = "InPlaceUpdateInProgress"

	// MachinesSpecUpToDateReason documents that the spec of all machines controlled by the TalosControlPlane is up to date.
	MachinesSpecUpToDateReason = "MachinesSpecUpToDate"
)

const (
	// ResizedCondition documents a TalosControlPlane that is resizing the set of controlled machines.
	ResizedCondition = "Resized"

	// ScalingUpReason (Severity=Info) documents a TalosControlPlane that is increasing the number of replicas.
	ScalingUpReason = "ScalingUp"

	// ScalingDownReason (Severity=Info) documents a TalosControlPlane that is decreasing the number of replicas.
	ScalingDownReason = "ScalingDown"

	// ResizedReason documents that the TalosControlPlane has reached the desired number of replicas.
	ResizedReason = "Resized"
)

const (
	// ControlPlaneComponentsHealthyCondition reports the overall status of control plane components
	// implemented as static pods generated by Talos including kube-api-server, kube-controller manager,
	// kube-scheduler and etcd.
	ControlPlaneComponentsHealthyCondition = "ControlPlaneComponentsHealthy"

	// ControlPlaneComponentsUnhealthyReason (Severity=Error) documents a control plane component not healthy.
	ControlPlaneComponentsUnhealthyReason = "ControlPlaneComponentsUnhealthy"

	// ControlPlaneComponentsInspectionFailedReason documents a failure in inspecting the control plane component status.
	ControlPlaneComponentsInspectionFailedReason = "ControlPlaneComponentsInspectionFailed"

	// ControlPlaneComponentsHealthyReason documents that all control plane components are healthy.
	ControlPlaneComponentsHealthyReason = "ControlPlaneComponentsHealthy"
)

const (
	// EtcdClusterHealthyCondition documents the overall etcd cluster's health.
	EtcdClusterHealthyCondition = "EtcdClusterHealthyCondition"

	// EtcdClusterUnhealthyReason (Severity=Error) is set when the etcd cluster is unhealthy.
	EtcdClusterUnhealthyReason = "EtcdClusterUnhealthy"

	// EtcdClusterHealthyReason documents that the etcd cluster is healthy.
	EtcdClusterHealthyReason = "EtcdClusterHealthy"

	// EtcdClusterQuorumLostReason (Severity=Error) is set when too few etcd members are healthy for etcd to keep quorum.
	EtcdClusterQuorumLostReason = "EtcdClusterQuorumLost"

	// EtcdClusterInspectionFailedReason is set when the etcd service could not be inspected on any control plane
	// machine, or on enough of them for the quorum to be unknown.
	EtcdClusterInspectionFailedReason = "EtcdClusterInspectionFailed"
)

const (
	// MachinesCreatedCondition documents that the machines controlled by the TalosControlPlane are created.
	// When this condition is false, it indicates that there was an error when cloning the infrastructure/bootstrap template or
	// when generating the machine object.
	MachinesCreatedCondition = "MachinesCreated"

	// InfrastructureTemplateCloningFailedReason (Severity=Error) documents a TalosControlPlane failing to
	// clone the infrastructure template.
	InfrastructureTemplateCloningFailedReason = "InfrastructureTemplateCloningFailed"

	// BootstrapTemplateCloningFailedReason (Severity=Error) documents a TalosControlPlane failing to
	// clone the bootstrap template.
	BootstrapTemplateCloningFailedReason = "BootstrapTemplateCloningFailed"

	// MachineGenerationFailedReason (Severity=Error) documents a TalosControlPlane failing to
	// generate a machine object.
	MachineGenerationFailedReason = "MachineGenerationFailed"

	// MachinesCreatedReason documents that the TalosControlPlane has successfully created all required machines.
	MachinesCreatedReason = "MachinesCreated"
)

const (
	// RemediatingCondition surfaces details about the ongoing remediation of the control plane Machines, if any.
	RemediatingCondition = clusterv1.RemediatingCondition

	// RemediatingReason surfaces when the TalosControlPlane has at least one Machine with HealthCheckSucceeded
	// set to false and OwnerRemediated set to false.
	RemediatingReason = clusterv1.RemediatingReason

	// NotRemediatingReason surfaces when the TalosControlPlane has no Machine with HealthCheckSucceeded set to
	// false and OwnerRemediated set to false.
	NotRemediatingReason = clusterv1.NotRemediatingReason

	// RemediatingInternalErrorReason surfaces unexpected failures when computing the Remediating condition.
	RemediatingInternalErrorReason = clusterv1.InternalErrorReason
)

// Reasons of the OwnerRemediated condition of the control plane Machines; same values as the KubeadmControlPlane's.
const (
	// MachineRemediationInternalErrorReason surfaces unexpected failures while remediating a control plane Machine.
	MachineRemediationInternalErrorReason = clusterv1.InternalErrorReason

	// MachineCannotBeRemediatedReason surfaces when the remediation of a control plane Machine can't be started,
	// because it could cost etcd its quorum or the retry limits are reached, say. It needs an operator.
	MachineCannotBeRemediatedReason = "CannotBeRemediated"

	// MachineRemediationDeferredReason surfaces when the remediation of a control plane Machine must be deferred,
	// until another Machine finishes provisioning or deleting, say.
	MachineRemediationDeferredReason = "RemediationDeferred"

	// MachineRemediationMachineDeletingReason surfaces when the remediation of a control plane Machine has been
	// completed by deleting the unhealthy Machine. A new Machine is created by the TalosControlPlane as part of the
	// regular reconcile loop that ensures the desired number of replicas exist.
	MachineRemediationMachineDeletingReason = "MachineDeleting"
)
